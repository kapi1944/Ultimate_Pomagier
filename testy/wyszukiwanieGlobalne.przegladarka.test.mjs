test('responsywność nagłówka oraz mobilna lupa i powrót focusu', { timeout: 60000 }, async () => {
  const przegladarka = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const strona = await przegladarka.newPage()
    await strona.goto(adres)
    await strona.getByRole('button', { name: 'Otwórz demonstrację Architekta', exact: true }).click()
    await mkdir('tmp/wyszukiwanie', { recursive: true })
    for (const szerokosc of [1920, 1440, 1024, 768, 760, 390, 320]) {
      await strona.setViewportSize({ width: szerokosc, height: 900 })
      const pole = strona.getByRole('combobox', { name: 'Szukaj w Pomagierze' })
      if (szerokosc > 760) {
        await pole.waitFor({ state: 'visible' })
        if (szerokosc === 1440) {
          await pole.fill('szkolenia')
          await strona.locator('.wyszukiwarka__panel').getByRole('option').first().waitFor()
          await strona.screenshot({ path: 'tmp/wyszukiwanie/desktop.png' })
          await pole.press('Escape')
        }
      } else {
        const lupa = strona.getByRole('button', { name: 'Otwórz wyszukiwarkę' })
        await lupa.click()
        await pole.waitFor({ state: 'visible' })
        await strona.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Szukaj w Pomagierze')
        assert.equal(await strona.locator('.wyszukiwarka kbd').isVisible(), false)
        await pole.fill('klienci')
        await strona.locator('.wyszukiwarka__panel').getByRole('option').first().waitFor()
        const panel = await strona.locator('.wyszukiwarka__panel').boundingBox()
        assert.ok(panel.x >= 0 && panel.x + panel.width <= szerokosc)
        if (szerokosc === 390) await strona.screenshot({ path: 'tmp/wyszukiwanie/mobilna.png' })
        await pole.press('Escape')
        assert.equal(await lupa.evaluate((element) => element === document.activeElement), true)
      }
      const naglowek = strona.locator('.naglowek-aplikacji')
      assert.ok(await naglowek.getByRole('button', { name: 'Wyloguj', exact: true }).isVisible())
      assert.equal(await naglowek.evaluate((element) => element.scrollWidth <= element.clientWidth + 1), true, String(szerokosc))
    }
  } finally { await przegladarka.close() }
})

